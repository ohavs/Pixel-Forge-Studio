# Builds the Orbit Studio icon (recreation of the Canva concept) as SVG + Android vector drawables.
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import cairosvg

def text_path(font_file, text, size, cx, baseline, tracking=0.0):
    f = TTFont(font_file); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
    s = size / upm
    names = [cmap[ord(c)] for c in text]
    widths = [gs[n].width * s for n in names]
    total = sum(widths) + tracking * size * (len(text) - 1)
    x = cx - total / 2; out = []
    for n, w in zip(names, widths):
        pen = SVGPathPen(gs, ntos=lambda v: ("%.2f" % v).rstrip('0').rstrip('.'))
        gs[n].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        out.append(pen.getCommands()); x += w + tracking * size
    return " ".join(out)

C = 54  # centre of the 108 adaptive canvas
R, SW = 28, 3.4
orbit = text_path('/usr/share/fonts/opentype/inter/InterDisplay-ExtraBold.otf', 'ORBIT', 14.5, C, 57.2, 0.01)
studio = text_path('/usr/share/fonts/opentype/inter/Inter-SemiBold.otf', 'STUDIO', 4.3, C, 65.6, 0.32)
import math
a = math.radians(-50); dx, dy = C + R * math.cos(a), C + R * math.sin(a)
ring = f"M{C-R},{C}a{R},{R} 0 1,0 {2*R},0a{R},{R} 0 1,0 {-2*R},0"
dot = lambda r: f"M{dx-r:.2f},{dy:.2f}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0"

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#080A2E"/><stop offset=".55" stop-color="#14104A"/><stop offset="1" stop-color="#4A22B8"/></linearGradient>
<linearGradient id="ring" gradientUnits="userSpaceOnUse" x1="24" y1="84" x2="84" y2="24"><stop offset="0" stop-color="#6C4CF5"/><stop offset=".6" stop-color="#A48CFF"/><stop offset="1" stop-color="#E9E2FF"/></linearGradient>
<radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="{dx:.2f}" cy="{dy:.2f}" r="10"><stop offset="0" stop-color="#FF6A4D" stop-opacity=".55"/><stop offset="1" stop-color="#FF6A4D" stop-opacity="0"/></radialGradient>
<radialGradient id="dot" gradientUnits="userSpaceOnUse" cx="{dx-1.5:.2f}" cy="{dy-1.5:.2f}" r="5.5"><stop offset="0" stop-color="#FFA184"/><stop offset="1" stop-color="#F2452C"/></radialGradient></defs>
<rect width="108" height="108" fill="url(#bg)"/>
<path d="{ring}" fill="none" stroke="url(#ring)" stroke-width="{SW}"/>
<path d="{dot(10)}" fill="url(#glow)"/><path d="{dot(4.6)}" fill="url(#dot)"/>
<path d="{orbit}" fill="#FFFFFF"/><path d="{studio}" fill="#CFC4FF"/>
</svg>'''
open(sys.argv[1] + '/icon.svg', 'w').write(svg)
cairosvg.svg2png(bytestring=svg.encode(), write_to=sys.argv[1] + '/icon-512.png', output_width=512, output_height=512)

head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Orbit Studio mark (design/logo/orbit-final, from the Canva concept). Generated by design/logo/orbit-final/logo.py. -->\n'
vec = '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
def lin(x1, y1, x2, y2, stops):
    return f'<aapt:attr name="android:{{}}"><gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">' + "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops) + '</gradient></aapt:attr>'
def rad(cx, cy, r, stops):
    return f'<aapt:attr name="android:{{}}"><gradient android:type="radial" android:centerX="{cx:.2f}" android:centerY="{cy:.2f}" android:gradientRadius="{r}">' + "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops) + '</gradient></aapt:attr>'
ringG = lin(24, 84, 84, 24, [(0, '#FF6C4CF5'), (.6, '#FFA48CFF'), (1, '#FFE9E2FF')]).format('strokeColor')
glowG = rad(dx, dy, 10, [(0, '#8CFF6A4D'), (1, '#00FF6A4D')]).format('fillColor')
dotG = rad(dx - 1.5, dy - 1.5, 5.5, [(0, '#FFFFA184'), (1, '#FFF2452C')]).format('fillColor')
fg = head + vec + f'''    <path android:pathData="{ring}" android:strokeWidth="{SW}">{ringG}</path>
    <path android:pathData="{dot(10)}">{glowG}</path>
    <path android:pathData="{dot(4.6)}">{dotG}</path>
    <path android:fillColor="#FFFFFF" android:pathData="{orbit}"/>
    <path android:fillColor="#CFC4FF" android:pathData="{studio}"/>
</vector>
'''
mono = head + vec + f'''    <path android:pathData="{ring}" android:strokeWidth="{SW}" android:strokeColor="#FFFFFF"/>
    <path android:fillColor="#FFFFFF" android:pathData="{dot(4.6)}"/>
    <path android:fillColor="#FFFFFF" android:pathData="{orbit}"/>
    <path android:fillColor="#FFFFFF" android:pathData="{studio}"/>
</vector>
'''
bg = head + vec + '    <path android:pathData="M0,0h108v108h-108z">' + lin(0, 0, 108, 108, [(0, '#FF080A2E'), (.55, '#FF14104A'), (1, '#FF4A22B8')]).format('fillColor') + '</path>\n</vector>\n'
for mod in ('app', 'wear'):
    d = f'/home/user/Pixel-Forge-Studio/{mod}/src/main/res/drawable/'
    open(d + 'ic_fg.xml', 'w').write(fg); open(d + 'ic_bg.xml', 'w').write(bg); open(d + 'ic_mono.xml', 'w').write(mono)
